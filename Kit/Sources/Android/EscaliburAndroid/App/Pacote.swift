    static func abrir(nome: String, versao: String, build: String, idioma: String) {
        self.idioma = idioma
        self.versao = "\(versao) (\(build))"
        guard !lido else { return }
        lido = true
        #if !DEBUG
        marca = avaliar(nome: nome, versao: versao, build: build)
        #endif
    }

    /// So o que veio no app: a lista dentro do APK.
    private static func avaliar(nome: String, versao: String, build: String) -> String? {
        let atual = "\(versao) (\(build))"
        guard let pasta = CoreResources.directory,
              let dados = try? Data(contentsOf: URL(fileURLWithPath: pasta).appendingPathComponent(d(o)).appendingPathComponent(d(n) + "." + d(x))),
              let chave = try? P256.Signing.PublicKey(rawRepresentation: b(k)) else { return atual }
        let lista = try? ReleaseManifest.verified(dados, app: nome, keys: [d(i): chave], threshold: 1)
        let certo = lista?.versions.contains { $0.version == versao && $0.builds.contains(build) } ?? false
        return certo ? nil : atual
    }

