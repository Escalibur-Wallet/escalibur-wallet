        let texto = (idioma.hasPrefix("pt") ? p : e).map(d)
        return Aviso(titulo: texto[0], mensagem: texto[1].replacingOccurrences(of: "%@", with: marca), seguroTitulo: texto[2],
                     seguroTexto: texto[3], passos: [texto[4]], nota: texto[6], rodape: texto[5])
    }

    private static func b(_ bytes: [UInt8]) -> Data {
